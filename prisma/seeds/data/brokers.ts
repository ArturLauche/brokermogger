function defineBroker(input: BrokerSeedInput): BrokerSeed {
  const { seedSources, ...rest } = input;
  return {
    ...rest,
    productionSendingEnabled: false,
    isDemoData: true,
    seedSources: seedSources ?? [
      {
        sourceTitle: `${input.legalName} demo profile`,
        sourceType: "DEMO_FICTIONAL",
        retrievedAt: RETRIEVED_AT,
        isDemo: true,
        notes: DEMO_SOURCE_NOTE,
      },
    ],
  };
}


/**
 * Fictional demo brokers.
 *
 * Every record in this file is invented. There are no real company names, no
 * real domains and no real contact addresses, and every domain ends in
 * `.example` or `.invalid` so that nothing can be sent anywhere by accident.
 * The reasons are described in `docs/broker-seed-data.md`: Brokermogger does
 * not scrape, does not copy a third party broker database and does not publish
 * unverified claims about real companies.
 *
 * `defineBroker` forces `isDemoData` to true and `productionSendingEnabled` to
 * false, so the data list below cannot switch either of them on. The database
 * additionally refuses production sending without full verification.
 *
 * Pure data: no database access, only enum types from @prisma/client.
 */
import type {
  BrokerAliasKind,
  BrokerCategory,
  BrokerRiskTier,
  BrokerVerificationStatus,
  ContactMethodType,
  CoverageType,
  DataCategory,
  LegalConfidence,
  RequestType,
  SeedSourceType,
} from "@prisma/client";

export interface BrokerAliasSeed {
  alias: string;
  kind: BrokerAliasKind;
}

export interface BrokerContactMethodSeed {
  type: ContactMethodType;
  value: string;
  label: string;
  isPreferred: boolean;
  isVerified: boolean;
  /** ISO timestamp, only set together with `isVerified`. */
  verifiedAt?: string;
  verifiedBy?: string;
  verificationNote?: string;
  sourceUrl?: string;
  priority: number;
  isActive: boolean;
}

export interface BrokerCoverageSeed {
  jurisdictionCode: string;
  coverageType: CoverageType;
  supportedRequestTypes: RequestType[];
  confidence: LegalConfidence;
  notes: string;
  isActive: boolean;
}

export interface BrokerSeedSourceSeed {
  sourceTitle: string;
  sourceType: SeedSourceType;
  sourceUrl?: string;
  /** ISO timestamp. */
  retrievedAt: string;
  isDemo: boolean;
  notes: string;
}

/**
 * Stored as JSON on `Broker.verificationRequirements`. Declared as a type
 * alias, not an interface, so that Prisma accepts it as a JSON input value.
 */
export type BrokerVerificationRequirementsSeed = {
  identityDocument: boolean;
  accountRequired: boolean;
  notarised: boolean;
  notes: string;
};

/** Stored as JSON on `Broker.knownResponseBehavior`. */
export type BrokerResponseBehaviorSeed = {
  typicalResponseDays: number | null;
  autoResponder: boolean;
  commonRejectionReasons: string[];
  notes: string;
};

export interface BrokerSeed {
  slug: string;
  legalName: string;
  tradingNames: string[];
  websiteUrl: string;
  category: BrokerCategory;
  subcategories: string[];
  countriesServed: string[];
  regionsServed: string[];
  dataCategories: DataCategory[];
  privacyEmail?: string;
  privacyRequestUrl?: string;
  optOutUrl?: string;
  webFormUrl?: string;
  postalAddress?: string;
  apiSupported: boolean;
  apiNotes?: string;
  verificationRequirements: BrokerVerificationRequirementsSeed;
  knownResponseBehavior: BrokerResponseBehaviorSeed;
  confidenceScore: number;
  sourceUrl: string;
  /** ISO timestamp. Absent while nothing has been verified at all. */
  lastVerifiedAt?: string;
  manualReviewRequired: boolean;
  isActive: boolean;
  verificationStatus: BrokerVerificationStatus;
  /** Always false in demo data. */
  productionSendingEnabled: false;
  productionUnsafeFlag: boolean;
  /** Always true in demo data. */
  isDemoData: true;
  riskTier: BrokerRiskTier;
  notes: string;
  aliases: BrokerAliasSeed[];
  contactMethods: BrokerContactMethodSeed[];
  coverage: BrokerCoverageSeed[];
  seedSources: BrokerSeedSourceSeed[];
}

type BrokerSeedInput = Omit<
  BrokerSeed,
  "productionSendingEnabled" | "isDemoData" | "seedSources"
> & {
  seedSources?: BrokerSeedSourceSeed[];
};

